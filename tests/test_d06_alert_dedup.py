# D-06-3: ON CONFLICT DO NOTHING deduplication
# ---------------------------------------------------------------------------

class TestAlertDeduplication:
    def test_same_source_attack_window_deduped(self):
        """Two alerts with same source_ip + attack_type in same 5-min window → only 1 stored."""
        store, path = _make_store()
        try:
            ts = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="1.2.3.4",
                                   attack_type="portscan", timestamp=ts))
            # Same source, attack_type, within same 5-min bucket
            ts2 = datetime(2025, 1, 1, 12, 2, 30, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="1.2.3.4",
                                   attack_type="portscan", timestamp=ts2))
            alerts = store.list_alerts(limit=100)
            count_1234_portscan = sum(
                1 for a in alerts
                if a.get("source_ip") == "1.2.3.4" and a.get("attack_type") == "portscan"
            )
            assert count_1234_portscan == 1, (
                f"Expected 1 alert (deduped), got {count_1234_portscan}"
            )
        finally:
            os.unlink(path)

    def test_different_5min_window_not_deduped(self):
        """Same source + attack_type in different 5-min windows → both stored."""
        store, path = _make_store()
        try:
            ts1 = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc).isoformat()
            ts2 = datetime(2025, 1, 1, 12, 5, 0, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="2.3.4.5",
                                   attack_type="bruteforce", timestamp=ts1))
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="2.3.4.5",
                                   attack_type="bruteforce", timestamp=ts2))
            alerts = store.list_alerts(limit=100)
            count = sum(
                1 for a in alerts
                if a.get("source_ip") == "2.3.4.5" and a.get("attack_type") == "bruteforce"
            )
            assert count == 2, f"Expected 2 (different windows), got {count}"
        finally:
            os.unlink(path)

    def test_different_attack_type_not_deduped(self):
        """Same source + different attack_type in same window → both stored."""
        store, path = _make_store()
        try:
            ts = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="3.4.5.6",
                                   attack_type="portscan", timestamp=ts))
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="3.4.5.6",
                                   attack_type="bruteforce", timestamp=ts))
            alerts = store.list_alerts(limit=100)
            count = sum(1 for a in alerts if a.get("source_ip") == "3.4.5.6")
            assert count == 2
        finally:
            os.unlink(path)

    def test_different_source_ip_not_deduped(self):
        """Different source_ip with same attack_type + window → both stored."""
        store, path = _make_store()
        try:
            ts = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="4.5.6.7",
                                   attack_type="ddos", timestamp=ts))
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="8.9.10.11",
                                   attack_type="ddos", timestamp=ts))
            alerts = store.list_alerts(limit=100)
            sources = {a.get("source_ip") for a in alerts}
            assert "4.5.6.7" in sources
            assert "8.9.10.11" in sources
        finally:
            os.unlink(path)

    def test_empty_source_ip_not_deduped(self):
        """Alerts with empty source_ip bypass dedup (no dedup_key → NULL)."""
        store, path = _make_store()
        try:
            ts = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc).isoformat()
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="",
                                   attack_type="unknown", timestamp=ts))
            store.save_alert(_alert(alert_id=str(uuid.uuid4()), source_ip="",
                                   attack_type="unknown", timestamp=ts))
            alerts = store.list_alerts(limit=100)
            count = sum(1 for a in alerts if a.get("source_ip", "") == "")
            assert count == 2, "Empty source_ip alerts must not be deduped"
        finally:
            os.unlink(path)


