class TestAlertDedupKey:
    def setup_method(self):
        from src.ops_store import OpsStore
        self._fn = OpsStore._alert_dedup_key

    def test_same_inputs_same_key(self):
        ts = "2025-01-01T12:03:00+00:00"
        k1 = self._fn("1.2.3.4", "portscan", ts)
        k2 = self._fn("1.2.3.4", "portscan", ts)
        assert k1 == k2

    def test_different_5min_bucket_different_key(self):
        ts1 = "2025-01-01T12:00:00+00:00"
        ts2 = "2025-01-01T12:05:00+00:00"
        k1 = self._fn("1.2.3.4", "portscan", ts1)
        k2 = self._fn("1.2.3.4", "portscan", ts2)
        assert k1 != k2

    def test_same_5min_bucket_same_key(self):
        ts1 = "2025-01-01T12:00:00+00:00"
        ts2 = "2025-01-01T12:04:59+00:00"
        k1 = self._fn("1.2.3.4", "portscan", ts1)
        k2 = self._fn("1.2.3.4", "portscan", ts2)
        assert k1 == k2

    def test_empty_source_ip_returns_none(self):
        assert self._fn("", "portscan", "2025-01-01T12:00:00+00:00") is None

    def test_different_attack_type_different_key(self):
        ts = "2025-01-01T12:00:00+00:00"
        k1 = self._fn("1.2.3.4", "portscan", ts)
        k2 = self._fn("1.2.3.4", "bruteforce", ts)
        assert k1 != k2
