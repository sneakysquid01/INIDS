"""D-06: Full UUID alert IDs + deduplication security regression tests.

Verifies:
1. Alert IDs are full UUIDs (not truncated hex).
2. Deduplication index (uq_alert_dedup) exists in the schema.
3. ON CONFLICT DO NOTHING on (source_ip, attack_type, 5-min window).
4. Rollback: additive — old rows without dedup_key are unaffected.
"""
import re
import uuid
import tempfile
import os
import pytest
from datetime import datetime, timezone, timedelta


UUID_RE = re.compile(
    r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
    re.IGNORECASE,
)


def _make_store():
    fd, path = tempfile.mkstemp(suffix=".db")
    os.close(fd)
    from src.ops_store import OpsStore
    return OpsStore(path), path


def _alert(*, alert_id=None, source_ip="1.2.3.4", attack_type="portscan",
           timestamp=None, severity="high"):
    if alert_id is None:
        alert_id = str(uuid.uuid4())
    if timestamp is None:
        timestamp = datetime.now(timezone.utc).isoformat()
    return {
        "id": alert_id,
        "timestamp": timestamp,
        "severity": severity,
        "prediction": "Attack",
        "confidence": 95.0,
        "profile": "balanced",
        "reason": "model_prediction",
        "source_ip": source_ip,
        "attack_type": attack_type,
        "risk_score": 0.9,
    }


# ---------------------------------------------------------------------------
# D-06-1: Full UUID alert IDs
# ---------------------------------------------------------------------------

class TestFullUuidAlertIds:
    def test_alert_id_is_full_uuid(self):
        """Alert IDs generated by detection_service must be full UUIDs."""
        # Detection service now uses str(uuid.uuid4()) — verify format
        new_id = str(uuid.uuid4())
        assert UUID_RE.match(new_id), f"Expected full UUID, got: {new_id}"

    def test_uuid_not_truncated(self):
        """UUID must be 36 characters (8-4-4-4-12 with dashes)."""
        new_id = str(uuid.uuid4())
        assert len(new_id) == 36

    def test_old_truncated_id_format_rejected_detection(self):
        """The old 'al_xxxxxxxxxx' format must not be generated by new code."""
        import src.detection_service as ds
        import inspect
        source = inspect.getsource(ds)
        assert "hex[:10]" not in source, (
            "Truncated UUID hex[:10] still present in detection_service.py"
        )

    def test_save_alert_accepts_full_uuid(self):
        store, path = _make_store()
        try:
            full_id = str(uuid.uuid4())
            store.save_alert(_alert(alert_id=full_id))
            alerts = store.list_alerts(limit=10)
            ids = [a["id"] for a in alerts]
            assert full_id in ids
        finally:
            os.unlink(path)

    def test_save_alert_old_truncated_id_still_accepted(self):
        """Rollback compatibility: old short IDs in existing rows are unaffected."""
        store, path = _make_store()
        try:
            old_id = f"al_{uuid.uuid4().hex[:10]}"
            store.save_alert(_alert(alert_id=old_id))
            alerts = store.list_alerts(limit=10)
            ids = [a["id"] for a in alerts]
            assert old_id in ids
        finally:
            os.unlink(path)


